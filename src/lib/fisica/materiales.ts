export function obtenerDielectricoPorId(
  _id: string,
): MaterialDielectrico {
  const encontrado = CATALOGO_DIELECTRICOS.find(
    (_material) => _material.id === _id,
  );
  return encontrado ?? CATALOGO_DIELECTRICOS[1];
}

export function obtenerMedioPorId(_id: string): MedioElectromagnetico {
  const encontrado = CATALOGO_MEDIOS_CONDUCTORES.find(
    (_medio) => _medio.id === _id,
  );
  return encontrado ?? CATALOGO_MEDIOS_CONDUCTORES[0];
}
